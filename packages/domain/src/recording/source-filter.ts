/**
 * Input source filtering and physical press state tracking for recording sessions.
 */

import {
  type MacroEvent,
  type MouseButton,
  type RecordingOptions,
  type HotkeyBinding,
  MacroEventType,
} from '../model/types.js';

/**
 * Extracts reserved virtual key codes from management hotkey bindings.
 */
export function extractIgnoredVirtualKeys(
  hotkeys?: readonly (HotkeyBinding | null | undefined)[],
): Set<number> {
  const result = new Set<number>();
  if (!hotkeys) return result;
  for (const hotkey of hotkeys) {
    if (hotkey && hotkey.virtualKey !== 0) {
      result.add(hotkey.virtualKey);
    }
  }
  return result;
}

/**
 * Extracts reserved mouse buttons from management hotkey bindings.
 */
export function extractIgnoredMouseButtons(
  hotkeys?: readonly (HotkeyBinding | null | undefined)[],
): Set<MouseButton> {
  const result = new Set<MouseButton>();
  if (!hotkeys) return result;
  for (const hotkey of hotkeys) {
    if (hotkey && hotkey.mouseButton !== 'None') {
      result.add(hotkey.mouseButton);
    }
  }
  return result;
}

/**
 * Determines if an incoming macro event should be recorded according to user options
 * and configured management hotkeys.
 *
 * Covers:
 * - Disabled sources return false immediately and do not start or advance the session clock.
 * - Configured management hotkeys return false and never enter the recorded timeline.
 */
export function shouldRecordEvent(
  item: MacroEvent,
  options: RecordingOptions,
  ignoredVirtualKeys: ReadonlySet<number>,
  ignoredMouseButtons: ReadonlySet<MouseButton>,
): boolean {
  if (
    (item.type === MacroEventType.KeyDown || item.type === MacroEventType.KeyUp) &&
    ignoredVirtualKeys.has(item.virtualKey)
  ) {
    return false;
  }

  if (
    (item.type === MacroEventType.MouseButtonDown || item.type === MacroEventType.MouseButtonUp) &&
    ignoredMouseButtons.has(item.button)
  ) {
    return false;
  }

  switch (item.type) {
    case MacroEventType.KeyDown:
    case MacroEventType.KeyUp:
      return options.keyboard;

    case MacroEventType.MouseMove:
      return options.mouseMovement;

    case MacroEventType.MouseButtonDown:
    case MacroEventType.MouseButtonUp:
      return options.mouseButtons;

    case MacroEventType.Wheel:
    case MacroEventType.HorizontalWheel:
      return options.mouseWheel;

    case MacroEventType.GamepadButtonDown:
    case MacroEventType.GamepadButtonUp:
    case MacroEventType.GamepadAxis:
      return options.gamepad;

    default:
      return true;
  }
}

/**
 * Tracks physical press state to enforce exactly one KeyDown and KeyUp per physical action:
 * - Auto-repeat KeyDown messages generated by OS while a key is held are swallowed.
 * - Orphaned KeyUp messages (key was already held prior to recording start) are swallowed.
 * - Mouse buttons and gamepad buttons are tracked symmetrically.
 */
export class PressStateTracker {
  private readonly pressedKeys = new Set<number>();
  private readonly pressedButtons = new Set<MouseButton>();
  private readonly pressedGamepadButtons = new Set<string>();

  reset(): void {
    this.pressedKeys.clear();
    this.pressedButtons.clear();
    this.pressedGamepadButtons.clear();
  }

  /**
   * Evaluates and updates press state for an item.
   * Returns true if the event represents a genuine state transition;
   * returns false to suppress auto-repeats or orphaned releases.
   */
  trackPressState(item: MacroEvent): boolean {
    switch (item.type) {
      case MacroEventType.KeyDown:
        if (this.pressedKeys.has(item.virtualKey)) return false;
        this.pressedKeys.add(item.virtualKey);
        return true;

      case MacroEventType.KeyUp:
        if (!this.pressedKeys.has(item.virtualKey)) return false;
        this.pressedKeys.delete(item.virtualKey);
        return true;

      case MacroEventType.MouseButtonDown:
        if (this.pressedButtons.has(item.button)) return false;
        this.pressedButtons.add(item.button);
        return true;

      case MacroEventType.MouseButtonUp:
        if (!this.pressedButtons.has(item.button)) return false;
        this.pressedButtons.delete(item.button);
        return true;

      case MacroEventType.GamepadButtonDown: {
        const key = `${item.padIndex}:${item.gamepadButton}`;
        if (this.pressedGamepadButtons.has(key)) return false;
        this.pressedGamepadButtons.add(key);
        return true;
      }

      case MacroEventType.GamepadButtonUp: {
        const key = `${item.padIndex}:${item.gamepadButton}`;
        if (!this.pressedGamepadButtons.has(key)) return false;
        this.pressedGamepadButtons.delete(key);
        return true;
      }

      default:
        return true;
    }
  }

  isKeyPressed(virtualKey: number): boolean {
    return this.pressedKeys.has(virtualKey);
  }

  isButtonPressed(button: MouseButton): boolean {
    return this.pressedButtons.has(button);
  }

  isGamepadButtonPressed(padIndex: number, button: string): boolean {
    return this.pressedGamepadButtons.has(`${padIndex}:${button}`);
  }

  getHeldKeys(): readonly number[] {
    return Array.from(this.pressedKeys);
  }

  getHeldButtons(): readonly MouseButton[] {
    return Array.from(this.pressedButtons);
  }
}
